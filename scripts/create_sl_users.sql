CREATE TABLE SL_USERS 
   (	USER_ID NUMBER(8,0) NOT NULL ENABLE, 
	USER_NAME VARCHAR2(20 BYTE) NOT NULL ENABLE, 
	PASSWORD VARCHAR2(50 BYTE) NOT NULL ENABLE, 
	LOCATION CHAR(10 BYTE) NOT NULL ENABLE, 
	STATUS NUMBER(1,0) NOT NULL ENABLE, 
	LAST_LOGIN DATE, 
	LOGIN_KEY VARCHAR2(400 BYTE), 
	ROLE_ID NUMBER(5,0) NOT NULL ENABLE, 
	CR_DATE DATE, 
	DISPLAY_NAME VARCHAR2(50 BYTE) NOT NULL ENABLE, 
	DELETED NUMBER(1,0), 
	CREATED DATE, 
	CREATED_BY NUMBER(8,0), 
	LAST_EDITED_BY NUMBER(8,0), 
	LAST_EDITED DATE, 
	HAS_DASH NUMBER(1,0) DEFAULT 0, 
	ACCESSTOKEN VARCHAR2(500 BYTE), 
	 CONSTRAINT SL_USERS_SM_ROLES_FK FOREIGN KEY (ROLE_ID)
	  REFERENCES SLAPROD.SL_ROLES (ROLE_ID) ENABLE
   CREATE TABLE SL_CONFIG
   (	CONFIG_ID NUMBER(10,0), 
	KEY VARCHAR2(35 BYTE) NOT NULL ENABLE, 
	VALUE VARCHAR2(200 BYTE) NOT NULL ENABLE, 
	CR_DT DATE, 
	CR_BY NUMBER(10,0), 
	LAST_EDIT_BY NUMBER(10,0), 
	LAST_EDITED DATE, 
	GROUPS VARCHAR2(10 BYTE) NOT NULL ENABLE, 
	REMARKS VARCHAR2(100 BYTE)
   )  ;


CREATE TABLE SL_APP_LOGGING
   (	USER_ID NUMBER(8,0), 
	USER_NAME VARCHAR2(20 BYTE) NOT NULL ENABLE, 
	CR_DATE DATE DEFAULT sysdate, 
	ACTION_RESULT CHAR(1 BYTE) DEFAULT 'S', 
	DEVICE_SIGNATURE VARCHAR2(200 BYTE)
   );
